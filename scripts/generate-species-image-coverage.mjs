#!/usr/bin/env node
import fs from 'fs';
import path from 'path';

const MAP_PATH = path.resolve(process.cwd(), 'data/speciesImageMap.ts');
const OUT_JSON = path.resolve(process.cwd(), 'reports/species-image-coverage.json');
const OUT_MD = path.resolve(process.cwd(), 'reports/species-image-coverage.md');

function parseMap(content) {
  const entries = [];
  // Match keys like 'CODE': { ... }
  const entryRe = /'([^']+)':\s*\{([\s\S]*?)\},?/g;
  let m;
  while ((m = entryRe.exec(content)) !== null) {
    const code = m[1];
    const body = m[2];
    const slugMatch = /slug:\s*'([^']+)'/.exec(body);
    const nameMatch = /name:\s*'([^']+)'/.exec(body);
    const imageMatch = /image:\s*'([^']+)'/.exec(body);
    entries.push({ code, slug: slugMatch ? slugMatch[1] : null, name: nameMatch ? nameMatch[1] : null, image: imageMatch ? imageMatch[1] : null });
  }
  return entries;
}

function ensureDir(filePath) {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

try {
  const raw = fs.readFileSync(MAP_PATH, 'utf8');
  const entries = parseMap(raw);
  const total = entries.length;
  const mappedSlugs = entries.filter(e => e.slug).map(e => e.slug).sort();
  const missingSlugCount = entries.filter(e => !e.slug).length;

  ensureDir(OUT_JSON);
  fs.writeFileSync(OUT_JSON, JSON.stringify({ generated_at: new Date().toISOString(), total, missingSlugCount, entries }, null, 2));

  ensureDir(OUT_MD);
  const md = [];
  md.push('# Species Image Coverage Report');
  md.push('');
  md.push(`Generated: ${new Date().toISOString()}`);
  md.push('');
  md.push(`- Total mapped entries: **${total}**`);
  md.push(`- Entries missing ` + '`slug`' + `: **${missingSlugCount}**`);
  md.push('');
  md.push('## Mapped slugs (alphabetical)');
  md.push('');
  mappedSlugs.forEach(s => md.push(`- ${s}`));
  md.push('');
  md.push('## Notes');
  md.push('');
  md.push('- This report is generated by parsing `data/speciesImageMap.ts` textually.');
  md.push('- To compare against the `species` table in Supabase, provide a read-only `DATABASE_URL` and I can run a DB check.');

  fs.writeFileSync(OUT_MD, md.join('\n'));

  console.log('Report generated:', OUT_JSON, OUT_MD);
} catch (err) {
  console.error('Failed to generate report:', err);
  process.exit(1);
}
